// Get currently selected language
function getCurrentLanguage() {
    const savedLanguage = localStorage.getItem("selectedLanguage");
    return translations[savedLanguage] ? savedLanguage : "en";
}


// Get translated text using a key
function t(key) {
    const language = getCurrentLanguage();

    return translations[language]?.[key]
        || translations.en[key]
        || key;
}


// Apply translations to the current page
function applyTranslations(root = document) {
    const language = getCurrentLanguage();

    // Translate normal text
    root.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.getAttribute("data-i18n");

        if (translations[language]?.[key] || translations.en[key]) {
            element.textContent = t(key);
        }
    });

    // Translate placeholders
    root.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        const key = element.getAttribute("data-i18n-placeholder");
        element.setAttribute("placeholder", t(key));
    });

    // Translate title attributes
    root.querySelectorAll("[data-i18n-title]").forEach(element => {
        const key = element.getAttribute("data-i18n-title");
        element.setAttribute("title", t(key));
    });

    // Translate document title
    const pageTitle = document.querySelector("title[data-i18n]");
    if (pageTitle) {
        document.title = t(pageTitle.getAttribute("data-i18n"));
    }

    // Set language on HTML document
    document.documentElement.lang = language;
}


// Apply translations when page loads
document.addEventListener("DOMContentLoaded", function () {
    applyTranslations();
});
